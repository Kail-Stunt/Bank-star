package com.example.bank_start.dto;

import java.util.List;

/**
 * DTO для ответа с рекомендациями пользователя.
 *
 * <p>Содержит идентификатор пользователя и список рекомендованных продуктов.
 * Используется в ответе на GET-запрос {@code GET /recommendation/{user_id}}.
 *
 * <h3>Пример JSON:</h3>
 * <pre>
 * {
 *   "userId": "10000000-0000-0000-0000-000000000001",
 *   "recommendations": [
 *     {
 *       "name": "Простой кредит",
 *       "id": "ab138afb-f3ba-4a93-b74f-0fcee86d447f",
 *       "text": "Оформите кредит на выгодных условиях"
 *     }
 *   ]
 * }
 * </pre>
 *
 * <h3>Поля:</h3>
 * <ul>
 *   <li><b>userId</b> — идентификатор пользователя, для которого сформированы рекомендации.</li>
 *   <li><b>recommendations</b> — список рекомендованных продуктов. Может быть пустым.</li>
 * </ul>
 */
public record RecommendationDTO(
    /**
     * Идентификатор пользователя в строковом формате (UUID).
     */
    String userId,
    /**
     * Список рекомендованных продуктов. Может быть пустым, если рекомендаций нет.
     */
    List<RecommendationItem> recommendations
) {
    /**
     * DTO, представляющее отдельную рекомендацию продукта.
     *
     * <p>Содержит название продукта, идентификатор правила рекомендации
     * и текстовое описание.
     *
     * <h3>Пример JSON:</h3>
     * <pre>
     * {
     *   "name": "Простой кредит",
     *   "id": "ab138afb-f3ba-4a93-b74f-0fcee86d447f",
     *   "text": "Оформите кредит на выгодных условиях"
     * }
     * </pre>
     *
     * <h3>Поля:</h3>
     * <ul>
     *   <li><b>name</b> — название рекомендованного продукта или правила.</li>
     *   <li><b>id</b> — идентификатор правила рекомендации (UUID).</li>
     *   <li><b>text</b> — текстовое описание рекомендации.</li>
     * </ul>
     */
    public record RecommendationItem(
        /** Название рекомендованного продукта или правила. */
        String name,
        /** Идентификатор правила рекомендации (UUID в строковом формате). */
        String id,
        /** Текстовое описание рекомендации. */
        String text
    ) {}
}
